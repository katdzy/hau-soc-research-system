// Bundles the service code (src/services/actions.js and what it imports) for
// the `act` Cloud Function: functions/app/entry.js → functions/lib/app.js.
//
//   node scripts/functions/build.mjs           once (npm run build:functions; firebase.json predeploy)
//   node scripts/functions/build.mjs --watch   rebuild on change (docker compose `functions-build`)
//
// Swaps what only runs in a browser: the backend (functions/app/backend.js —
// Firestore through the Admin SDK, the server file store), Vite-only and
// browser-only modules (functions/app/stubs/browserOnly.js), and
// import.meta.env. The Admin SDK and firebase-functions stay external: they
// load from functions/node_modules.

import { context, build } from 'esbuild'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const at = (p) => path.join(root, p)

const SWAPS = new Map([
  [at('src/backend/index.js'), at('functions/app/backend.js')],
  [at('src/backend/sampleFiles.js'), at('functions/app/stubs/browserOnly.js')],
])
const BROWSER_PACKAGES = /^(@google\/genai|pdfjs-dist)(\/|$)/

const swap = {
  name: 'server-swaps',
  setup(b) {
    b.onResolve({ filter: /.*/ }, (args) => {
      if (BROWSER_PACKAGES.test(args.path)) return { path: at('functions/app/stubs/browserOnly.js') }
      if (!args.path.startsWith('.')) return null
      const target = SWAPS.get(path.resolve(args.resolveDir, args.path))
      return target ? { path: target } : null
    })
  },
}

const options = {
  entryPoints: [at('functions/app/entry.js')],
  outfile: at('functions/lib/app.js'),
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  external: ['firebase-admin', 'firebase-admin/*', 'firebase-functions', 'firebase-functions/*'],
  define: { 'import.meta.env': JSON.stringify({ MODE: 'production', DEV: false, PROD: true, VITE_BACKEND: 'firebase' }) },
  plugins: [swap],
  banner: { js: '// Generated by scripts/functions/build.mjs from src/ — do not edit.' },
  logLevel: 'info',
}

if (process.argv.includes('--watch')) {
  const ctx = await context(options)
  await ctx.watch()
} else {
  await build(options)
}
