// Forms are filled in and signed outside the system and uploaded back (Figma
// E-00/E-01, F-10). This file holds the pieces every form screen shares: the
// blank form library, opening an uploaded copy, and the two-step "download,
// sign outside, upload" field.

import { useState } from 'react'
import { files } from '../backend/index.js'
import { FORMS, MAX_PDF_MB } from '../domain/constants.js'
import { FORM_FILE_ACCEPT, formFileProblem } from '../domain/uploads.js'
import { latestCopy } from '../domain/forms.js'
import { FLAGS } from '../domain/flags.js'
import { Badge, fmtDate, fmtSize } from './ui.jsx'

// The blank templates the system stores (F-10), traced from Appendix C. The
// files are generated by scripts/dummy-docs (`--blanks`).
const BLANK_URLS = import.meta.glob('/test-fixtures/dummy-documents/blank-forms/*.pdf', { query: '?url', import: 'default', eager: true })
const blankFile = (prefix) => Object.entries(BLANK_URLS).find(([k]) => k.split('/').pop().startsWith(prefix)) ?? []

export const BLANK_FORMS = [
  { code: FORMS.F2003.code, name: 'Capstone/Thesis Monitoring Form', use: 'Weekly log — the group fills it in with the Adviser after each consultation and uploads it.' },
  { code: FORMS.F2004.code, name: FORMS.F2004.name, use: 'The Panel Chair uploads it with the verdict; the final copy carries the panel members’ signatures.' },
  { code: FORMS.F2005.code, name: FORMS.F2005.name, use: 'The Adviser recommends (or not) the group for the final defense; the Program Chair/Coordinator signs “Noted by”.' },
  { code: FORMS.APPROVAL.code, name: FORMS.APPROVAL.name, use: 'Signed in order: Adviser, panel, Program Chair/Coordinator, then the Dean and Associate Dean.' },
].map(f => {
  const [path, url] = blankFile(f.code === FORMS.APPROVAL.code ? 'ApprovalSheet' : f.code)
  return { ...f, url: url ?? null, fileName: path?.split('/').pop() ?? null }
})

export const blankOf = (code) => BLANK_FORMS.find(f => f.code === code) ?? null

export function BlankFormLink({ code, className = 'btn small', children }) {
  const blank = blankOf(code)
  if (!blank?.url) return <span className="faint small">Blank {code} not available</span>
  return <a className={className} href={blank.url} download={blank.fileName}>{children ?? `Download blank ${code}`}</a>
}

/**
 * Opens (or saves) an uploaded copy. Files are read through the file store,
 * never a public URL, so the storage rules decide who may.
 */
export function StoredFileLink({ storagePath, fileName, download = false, children }) {
  const [state, setState] = useState('idle')
  if (!storagePath) return null
  const open = async () => {
    setState('loading')
    try {
      const url = await files.url(storagePath)
      if (!url) return setState('missing')
      const a = document.createElement('a')
      a.href = url
      if (download) a.download = fileName ?? 'form'
      else { a.target = '_blank'; a.rel = 'noopener' }
      a.click()
      setState('idle')
    } catch {
      setState('error')
    }
  }
  return (
    <>
      <button type="button" className="quiet small" onClick={open} disabled={state === 'loading'}>
        {children ?? (download ? 'Download' : 'View')}
      </button>
      {state === 'missing' && <span className="faint small">The file is not in this browser’s store.</span>}
      {state === 'error' && <span className="error-text small">The file could not be opened.</span>}
    </>
  )
}

/** One uploaded copy: file, size, who uploaded it as what, when — read-only. */
export function CopyRow({ copy, nameOf }) {
  return (
    <div className="copy-row">
      <span className="mono small">{copy.fileName}</span>
      <span className="faint small">
        {copy.fileSize ? `${fmtSize(copy.fileSize)} · ` : ''}uploaded by {nameOf(copy.uploadedBy)} as {copy.role} · {fmtDate(copy.uploadedAt)}
      </span>
      <span className="inline">
        <StoredFileLink storagePath={copy.storagePath} fileName={copy.fileName} />
        <StoredFileLink storagePath={copy.storagePath} fileName={copy.fileName} download />
      </span>
    </div>
  )
}

const CHECKS = (code, group) => [
  'Every page is visible and readable',
  'All the required signatures are on the form, all signed the same way',
  `It is ${code} for ${group}`,
]

/** What the caller needs before it may submit: a file that passes, and every check ticked. */
export const signedCopyReady = (value) => !formFileProblem(value?.file) && value?.checks?.every(Boolean)

/**
 * E-00 + E-01 in one block: download the latest copy (or the blank form), sign
 * it outside the system, upload the signed copy. Controlled: `value` is
 * { file, checks }; `onChange` gets the next value.
 */
export function SignedCopyField({ formType, form = null, group, value, onChange, nameOf, intro }) {
  const latest = latestCopy(form)
  const checks = value?.checks ?? CHECKS(formType, group).map(() => false)
  const [fileKey, setFileKey] = useState(0)
  const problem = value?.file ? formFileProblem(value.file) : null
  const set = (patch) => onChange({ file: value?.file ?? null, checks, ...patch })

  return (
    <ol className="copy-steps">
      <li>
        <strong>Download {latest ? 'the latest copy' : 'the blank form'}</strong>
        <div className="inline mt-half">
          {latest
            ? <>
                <StoredFileLink storagePath={latest.storagePath} fileName={latest.fileName} download>Download latest copy</StoredFileLink>
                <span className="faint small">uploaded by {nameOf(latest.uploadedBy)} as {latest.role}, {fmtDate(latest.uploadedAt)}</span>
              </>
            : <BlankFormLink code={formType} />}
        </div>
      </li>
      <li>
        <strong>Sign it outside the system</strong>
        <p className="small muted m-0 mt-half">
          {intro ?? 'Fill it in and sign it.'} Everyone signs the same way — all e-signatures on the PDF, or all wet signatures on a printed copy, never mixed.
        </p>
      </li>
      <li>
        <strong>Upload the signed copy</strong>
        <div className="mt-half">
          <input key={fileKey} type="file" accept={FORM_FILE_ACCEPT} aria-label={`Signed ${formType}`}
            onChange={e => set({ file: e.target.files?.[0] ?? null })} />
          <div className="faint small mt-half">PDF, JPG or PNG — a scan or photo is fine. Up to {MAX_PDF_MB} MB. The file is kept exactly as uploaded.</div>
          {/* R9 — dev builds only: the walkthrough browser cannot open a file picker. */}
          {FLAGS.DEV_TOOLS && blankOf(formType)?.url && (
            <button type="button" className="quiet small mt-half" onClick={async () => {
              const blob = await (await fetch(blankOf(formType).url)).blob()
              setFileKey(k => k + 1)
              set({ file: new File([blob], `${formType.replace(/\s+/g, '')}_signed.pdf`, { type: 'application/pdf' }) })
            }}>
              Attach dummy signed copy <Badge tone="warn">dev</Badge>
            </button>
          )}
          {value?.file && !problem && <div className="mono small mt-half">{value.file.name} · {fmtSize(value.file.size)}</div>}
          {problem && <p className="small error-text mt-half" role="alert">{problem}</p>}
        </div>
        <fieldset className="choice mt-1">
          <legend className="label">Before you submit</legend>
          {CHECKS(formType, group).map((label, i) => (
            <label key={i} className="small inline">
              <input type="checkbox" checked={Boolean(checks[i])}
                onChange={e => set({ checks: checks.map((c, j) => (j === i ? e.target.checked : c)) })} />
              {label}
            </label>
          ))}
        </fieldset>
      </li>
    </ol>
  )
}
